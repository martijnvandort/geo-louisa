import { CONTINENT_COUNTRIES } from "./regions";

/** Sheet levels. Easy is Kids, Medium is Adults, Hard is Smart Adults. */
export type FootballLevel = "Kids" | "Adults" | "Smart Adults";
export type FootballPinKind = "city" | "stadium";

export type FootballQuestion = {
  id: string;
  level: FootballLevel;
  /** Country that owns the pin. Region filters use this, not the multiple-choice text. */
  country: string;
  maps: string[];
  promptEn: string;
  promptNl: string;
  /** Index 0 is the correct choice. */
  choicesEn: [string, string, string];
  choicesNl: [string, string, string];
  detailEn: string;
  detailNl: string;
  pinKind: FootballPinKind;
  pinNameEn: string;
  pinNameNl: string;
  coordinates: [number, number];
};

function mapsFor(country: string): string[] {
  const maps = ["world"];
  for (const [id, names] of Object.entries(CONTINENT_COUNTRIES)) {
    if (names.has(country)) maps.push(id);
  }
  if (country === "Netherlands") maps.push("netherlands");
  if (country === "United States") maps.push("united-states");
  return maps;
}

function q(
  id: string,
  level: FootballLevel,
  country: string,
  pinKind: FootballPinKind,
  pinNameEn: string,
  pinNameNl: string,
  coordinates: [number, number],
  promptEn: string,
  promptNl: string,
  choicesEn: [string, string, string],
  choicesNl: [string, string, string],
  detailEn: string,
  detailNl: string,
): FootballQuestion {
  return {
    id,
    level,
    country,
    maps: mapsFor(country),
    pinKind,
    pinNameEn,
    pinNameNl,
    coordinates,
    promptEn,
    promptNl,
    choicesEn,
    choicesNl,
    detailEn,
    detailNl,
  };
}

