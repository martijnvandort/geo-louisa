function sameAnswer(left: string, right: string): boolean {
  return left.trim().toLocaleLowerCase() === right.trim().toLocaleLowerCase();
}

const seen = new Set<string>();
for (const item of FOOTBALL) {
  if (seen.has(item.id)) throw new Error(`Duplicate football id ${item.id}`);
  seen.add(item.id);
  if (new Set(item.choicesEn).size !== 3 || new Set(item.choicesNl).size !== 3) {
    throw new Error(`Football choices are not unique: ${item.id}`);
  }
  if (sameAnswer(item.choicesEn[0], item.pinNameEn) || sameAnswer(item.choicesNl[0], item.pinNameNl)) {
    throw new Error(`Football pin repeats the answer: ${item.id}`);
  }
  if (!item.maps.includes("world")) throw new Error(`Football question missing World: ${item.id}`);
}
if (FOOTBALL.length < 100) throw new Error(`Expected about 100 football questions, got ${FOOTBALL.length}`);
for (const region of PLAY_REGIONS) {
  const kids = FOOTBALL.filter((item) => item.level === "Kids" && item.maps.includes(region));
  if (kids.length === 0) throw new Error(`No Easy football question in ${region}`);
}

const BY_ID = new Map(FOOTBALL.map((item) => [item.id, item]));

const LEVEL_RANK: Record<FootballLevel, number> = { Kids: 0, Adults: 1, "Smart Adults": 2 };

export function footballAllowed(level: FootballLevel, difficulty: "kids" | "normal" | "hard"): boolean {
  if (difficulty === "kids") return level === "Kids";
  if (difficulty === "normal") return LEVEL_RANK[level] <= 1;
  return true;
}

export function footballById(id: string): FootballQuestion | undefined {
  const bare = id.startsWith("football:") ? id.slice("football:".length) : id;
  return BY_ID.get(bare);
}

export function footballQuestionsFor(region: string, difficulty: "kids" | "normal" | "hard"): FootballQuestion[] {
  return FOOTBALL.filter((item) => item.maps.includes(region) && footballAllowed(item.level, difficulty));
}

export function footballCount(region: string, difficulty: "kids" | "normal" | "hard"): number {
  return footballQuestionsFor(region, difficulty).length;
}

function mulberry32(seed: number) {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Up to ten questions whose pin is on this map and whose level matches the difficulty. */
export function pickFootballIds(seed: number, region: string, difficulty: "kids" | "normal" | "hard"): string[] {
  const pool = footballQuestionsFor(region, difficulty).map((item) => item.id);
  const rng = mulberry32(seed);
  const picked: string[] = [];
  const take = Math.min(10, pool.length);
  for (let i = 0; i < take; i += 1) {
    const index = Math.floor(rng() * pool.length);
    const [id] = pool.splice(index, 1);
    if (id) picked.push(id);
  }
  return picked;
}

export function footballPlayPlace(id: string): {
  id: string;
  name: string;
  country: string;
  coordinates: [number, number];
} | null {
  const item = footballById(id);
  if (!item) return null;
  return {
    id: id.startsWith("football:") ? id : `football:${item.id}`,
    name: item.pinNameEn,
    country: item.country,
    coordinates: item.coordinates,
  };
}

export function footballQuizCard(
  id: string,
  locale: "en" | "nl",
  seed: number,
  roundIndex: number,
): { prompt: string; choices: string[]; correct: string; detail: string } | null {
  const item = footballById(id);
  if (!item) return null;
  const choices = locale === "nl" ? [...item.choicesNl] : [...item.choicesEn];
  const correct = choices[0] ?? "";
  const rng = mulberry32((seed + roundIndex * 17 + 3) >>> 0);
  for (let i = choices.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rng() * (i + 1));
    const swap = choices[i];
    choices[i] = choices[j] ?? swap;
    choices[j] = swap;
  }
  return {
    prompt: locale === "nl" ? item.promptNl : item.promptEn,
    choices,
    correct,
    detail: locale === "nl" ? item.detailNl : item.detailEn,
  };
}
